export function getPreferredLanguage(): Language {
  const value = navigator.language.toLowerCase();

  if (value.startsWith('pt')) {
    return 'pt-BR';
  }

  if (value.startsWith('es')) {
    return 'es';
  }

  return 'en-US';
}
